/// All 88 DMT rows in DMT ID order.
pub fn all() -> &'static [DmtTiming] {
    &TABLE
}

/// The row for a DMT ID (0x01-0x58).
pub fn by_id(id: u8) -> Option<&'static DmtTiming> {
    TABLE.iter().find(|t| t.id == id)
}

/// The row an EDID standard-timing code (two bytes, as stored) names directly.
pub fn by_std_code(b1: u8, b2: u8) -> Option<&'static DmtTiming> {
    let code = (u16::from(b1) << 8) | u16::from(b2);
    TABLE.iter().find(|t| t.std_code == Some(code))
}

/// The progressive row for a size and a refresh in whole hertz (matched on the rounded refresh).
/// Standard blanking is preferred over reduced blanking when both exist.
pub fn by_mode(width: u16, height: u16, refresh_hz: u32) -> Option<&'static DmtTiming> {
    let mut best: Option<&'static DmtTiming> = None;
    for t in TABLE.iter() {
        if t.width == width && t.height == height && !t.interlaced && t.refresh_hz() == refresh_hz {
            if t.blanking == Blanking::Standard {
                return Some(t);
            }
            best.get_or_insert(t);
        }
    }
    best
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn complete_and_ordered() {
        assert_eq!(all().len(), 0x58);
        for (i, t) in all().iter().enumerate() {
            assert_eq!(usize::from(t.id), i + 1, "ids run 0x01..=0x58");
            assert!(t.refresh_millihz > 0 && t.pixel_clock_khz > 0);
        }
    }

    #[test]
    fn known_rows() {
        let t = by_id(0x10).unwrap();
        assert_eq!((t.width, t.height, t.refresh_hz()), (1024, 768, 60));
        assert_eq!(
            (t.pixel_clock_khz, t.h_total, t.v_total),
            (65_000, 1344, 806)
        );
        assert_eq!(t.std_code, Some(0x6140));
        assert_eq!(t.refresh_millihz, 60_004);
        let t = by_id(0x04).unwrap();
        assert_eq!(
            (t.h_total, t.v_total, t.refresh_millihz),
            (800, 525, 59_940)
        );
        let t = by_id(0x0f).unwrap();
        assert!(t.interlaced);
        assert_eq!((t.v_total, t.refresh_hz()), (817, 87));
        let t = by_id(0x52).unwrap();
        assert_eq!(
            (t.width, t.height, t.pixel_clock_khz),
            (1920, 1080, 148_500)
        );
        assert_eq!(t.refresh_millihz, 60_000);
        let t = by_id(0x44).unwrap();
        assert_eq!(t.blanking, Blanking::ReducedV1);
        assert_eq!(by_id(0x58).unwrap().blanking, Blanking::ReducedV2Video);
        assert!(by_id(0).is_none() && by_id(0x59).is_none());
    }

    #[test]
    fn lookups() {
        assert_eq!(by_std_code(0x31, 0x59).unwrap().id, 0x07);
        assert_eq!(by_std_code(0xd1, 0xc0).unwrap().id, 0x52);
        assert!(by_std_code(0x01, 0x01).is_none());
        assert_eq!(by_mode(1280, 768, 60).unwrap().id, 0x17);
        assert_eq!(by_mode(1920, 1200, 60).unwrap().id, 0x45);
        assert_eq!(by_mode(2560, 1600, 60).unwrap().id, 0x4d);
        assert!(by_mode(1234, 567, 60).is_none());
    }

    #[test]
    fn std_codes_are_unique() {
        for (i, a) in all().iter().enumerate() {
            if a.std_code.is_none() {
                continue;
            }
            for b in &all()[i + 1..] {
                assert_ne!(a.std_code, b.std_code);
            }
        }
    }
}
