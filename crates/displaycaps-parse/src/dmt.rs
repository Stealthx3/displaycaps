//! The VESA Display Monitor Timings (DMT) table: every DMT ID from 0x01 to 0x58 with its active
//! size, refresh, blanking style, pixel clock and totals, plus the 2-byte EDID standard-timing
//! code where the standard defines one. Lookups by DMT ID, by standard-timing code and by mode.

use crate::cvt::Blanking;

/// One DMT row.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DmtTiming {
    /// The DMT ID (0x01-0x58).
    pub id: u8,
    /// Active width.
    pub width: u16,
    /// Active height (per frame).
    pub height: u16,
    /// Vertical refresh in millihertz (field rate if interlaced), derived from clock and totals.
    pub refresh_millihz: u32,
    /// Interlaced.
    pub interlaced: bool,
    /// Blanking style: `Standard` for GTF/CVT-standard and legacy rows, reduced for the "RB" rows.
    pub blanking: Blanking,
    /// Pixel clock in kHz.
    pub pixel_clock_khz: u32,
    /// Total pixels per line, borders included.
    pub h_total: u16,
    /// Total lines per frame (both fields and the half line if interlaced), borders included.
    pub v_total: u16,
    /// The EDID standard-timing code (first byte high), when the standard defines one.
    pub std_code: Option<u16>,
}

impl DmtTiming {
    /// The refresh rounded to whole hertz, as named in the DMT standard.
    pub fn refresh_hz(&self) -> u32 {
        (self.refresh_millihz + 500) / 1000
    }
}

#[allow(clippy::too_many_arguments)]
const fn row(
    id: u8,
    std: u16,
    width: u16,
    height: u16,
    interlaced: bool,
    blanking: Blanking,
    pixel_clock_khz: u32,
    h_total: u16,
    v_total: u16,
) -> DmtTiming {
    let fields: u64 = if interlaced { 2 } else { 1 };
    let den = h_total as u64 * v_total as u64;
    let num = pixel_clock_khz as u64 * 1_000_000 * fields;
    DmtTiming {
        id,
        width,
        height,
        refresh_millihz: ((num + den / 2) / den) as u32,
        interlaced,
        blanking,
        pixel_clock_khz,
        h_total,
        v_total,
        std_code: if std == 0 { None } else { Some(std) },
    }
}

